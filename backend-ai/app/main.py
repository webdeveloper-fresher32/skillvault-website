import os
import json
from contextlib import asynccontextmanager
from typing import AsyncGenerator
from fastapi import FastAPI, HTTPException
from fastapi.middleware.cors import CORSMiddleware
from fastapi.responses import StreamingResponse
from openai import AsyncOpenAI
from dotenv import load_dotenv

from app.rag.hybrid_retriever import HybridRAGRetriever
from app.schemas.rag import SearchRequest, ChatStreamRequest

load_dotenv()

OLLAMA_BASE_URL = os.getenv("OLLAMA_BASE_URL", "http://localhost:11434/v1")
CHAT_MODEL = os.getenv("CHAT_MODEL", "llama3.2")

retriever: HybridRAGRetriever = None
ollama_client: AsyncOpenAI = None


@asynccontextmanager
async def lifespan(app: FastAPI):
    # Initialize connection pool & FlashRank model once at startup
    global retriever, ollama_client
    print("🚀 Starting SkillVault AI Microservice...")
    retriever = HybridRAGRetriever()
    await retriever.initialize()
    ollama_client = AsyncOpenAI(base_url=OLLAMA_BASE_URL, api_key="ollama")
    print("   ✅ Service ready with local Ollama & FlashRank.")
    yield
    # Cleanup on shutdown
    if retriever:
        await retriever.close()
    print("🛑 SkillVault AI Microservice shut down.")


app = FastAPI(
    title="SkillVault AI Production RAG Service",
    version="1.0.0",
    lifespan=lifespan
)

# CORS configuration for Next.js frontend
app.add_middleware(
    CORSMiddleware,
    allow_origins=["http://localhost:3000", "http://127.0.0.1:3000"],
    allow_credentials=True,
    allow_methods=["*"],
    allow_headers=["*"],
)


@app.get("/health")
async def health():
    return {
        "status": "healthy",
        "service": "SkillVault AI Service",
        "models": {
            "embeddings": os.getenv("EMBEDDING_MODEL", "nomic-embed-text"),
            "chat": CHAT_MODEL
        }
    }


@app.post("/api/v1/rag/search")
async def search_endpoint(req: SearchRequest):
    """Hybrid Search (HNSW + BM25 + RRF + FlashRank) Endpoint."""
    try:
        results = await retriever.search(
            query=req.query,
            tenant_id=req.tenant_id,
            top_k=req.top_k
        )
        return {
            "query": req.query,
            "count": len(results),
            "results": results
        }
    except Exception as e:
        raise HTTPException(status_code=500, detail=str(e))


async def generate_rag_stream(
    query: str,
    tenant_id: str,
    top_k: int
) -> AsyncGenerator[str, None]:
    """
    Dual-stage SSE streaming generator:
    1. Retrieves & reranks Top-K passages.
    2. Emits verified citations event frame.
    3. Streams grounded answer tokens generated by local Llama 3.2.
    """
    # 1. Retrieve & Rerank
    passages = await retriever.search(query=query, tenant_id=tenant_id, top_k=top_k)

    citations = []
    context_blocks = []

    for idx, p in enumerate(passages, 1):
        meta = p.get("meta", {})
        doc_meta = meta.get("metadata", {})
        title = doc_meta.get("document_title", "Document")
        header = doc_meta.get("section_header", "Section")

        citations.append({
            "citation_index": idx,
            "chunk_id": p.get("id"),
            "document_title": title,
            "section_header": header,
           "score": round(float(p.get("score", 0.0)), 4)
        })

        context_blocks.append(
            f"--- [CITATION {idx}] (Document: {title} | Section: {header}) ---\n"
            f"{p.get('text')}\n"
        )

    context_str = "\n".join(context_blocks)

    # 2. Emit initial citation frame (protocol format: event + data)
    yield f"event: citations\ndata: {json.dumps(citations)}\n\n"

    # 3. Grounded Prompt Formulation
    system_prompt = (
        "You are SkillVault AI, an expert software engineering mentor.\n"
        "Answer the user's question accurately and concisely, strictly based on the provided documentation excerpts.\n"
        "Rules:\n"
        "1. Ground every claim in the documentation.\n"
        "2. When stating facts or explaining mechanisms, reference the relevant citation like [1], [2].\n"
        "3. Provide clean code examples when relevant.\n"
        "4. If the documentation does not contain enough info to answer, state that clearly."
    )

    user_prompt = (
        f"<context>\n{context_str}\n</context>\n\n"
        f"Question: {query}"
    )

    # 4. Stream tokens from local Ollama
    stream = await ollama_client.chat.completions.create(
        model=CHAT_MODEL,
        messages=[
            {"role": "system", "content": system_prompt},
            {"role": "user", "content": user_prompt}
        ],
        stream=True,
        temperature=0.2
    )

    async for chunk in stream:
        delta = chunk.choices[0].delta.content or ""
        if delta:
            payload = json.dumps({"token": delta})
            yield f"event: token\ndata: {payload}\n\n"

    # 5. Emit completion frame
    yield "event: done\ndata: {}\n\n"


@app.post("/api/v1/rag/chat/stream")
async def chat_stream_endpoint(req: ChatStreamRequest):
    """Server-Sent Events (SSE) streaming endpoint."""
    return StreamingResponse(
        generate_rag_stream(
            query=req.message,
            tenant_id=req.tenant_id,
            top_k=req.top_k
        ),
        media_type="text/event-stream",
        headers={
            "Cache-Control": "no-cache",
            "Connection": "keep-alive",
            "X-Accel-Buffering": "no"  # Bypasses NGINX reverse-proxy buffering
        }
    )